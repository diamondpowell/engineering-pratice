public public class FindAverage
{
    public static void main(String[] args)
    {
        //three parts of a loop
        //init
        //termination condition
        //update --> makes loop progress towards ending!!!
        int i = 1; //init
        int total = 0;
        while (i < 11)  //termination condition
        {
            total = total + i;//repeated code
            i++; //update
        }
        System.out.println("Total: " + total);
    }
} {
    
}
